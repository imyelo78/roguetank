// ---------------- 掩体 ----------------

const C_HEDGE = '#3f4d31';   // 树篱：诺曼底 6 月的深绿
const C_BANK = '#5b5342';    // 土堤：树篱底部的石土
const C_HOUSE = '#8c8375';   // 石灰岩农舍
const C_HOUSE2 = '#7d7568';
const C_BARN = '#6f6659';

/**
 * 树篱段。
 *
 * axis='z'：南北走向，x 固定，长度沿 z；axis='x'：东西走向。
 * 厚度 1.5 m、高 2.5 m —— 真实的 bocage 是 2~3 m 高的土堤加灌木，
 * 坦克撞不过去、平射炮弹也打不穿，只能从田口绕。
 * 这条正是"英军纵队为什么跑不掉"的地形前提：公路两侧全是墙。
 */
function hedgeZ(x, z0, z1, color = C_HEDGE) {
  const d = Math.abs(z1 - z0);
  return [x, (z0 + z1) / 2, 1.5, 2.5, d, color];
}
function hedgeX(z, x0, x1, color = C_HEDGE) {
  const w = Math.abs(x1 - x0);
  return [(x0 + x1) / 2, z, w, 2.5, 1.5, color];
}

/** 房屋：[x, z, w, h, d, color]。h 只影响渲染，碰撞只认 w/d */
function house(x, z, w, d, h = 7, color = C_HOUSE) {
  return [x, z, w, h, d, color];
}

/**
 * 全部掩体。顺序不重要，但**坐标是设计出来的，不参与随机扰动**——
 * 战役图必须每局一模一样，否则"背地形"这件事就变成了"背种子"。
 *
 * 内部用和 zones.js 一样的六元组写，读起来紧凑；出口统一转成
 * level.setLayout / generateBoxes 认识的对象形状，Game 不需要知道这个差异。
 */
export function buildVillersBoxes() {
  const b = [];

  // ---- 1. 公路两侧的连续树篱 ----
  //
  // 东侧 x=36：从镇口外一直铺到地图东南角。缺口是田口（真实 bocage 每块田
  // 都有一个 4~8 m 的入口，拖拉机进出用），也是玩家唯一能拐进田野的地方。
  b.push(hedgeZ(36, 96, 74));
  b.push(hedgeZ(36, 66, 54));      // 54~66 是 213 土路的缺口
  b.push(hedgeZ(36, 46, 26));
  b.push(hedgeZ(36, 18, -2));
  b.push(hedgeZ(36, -10, -16));

  // 西侧 x=10：同样连续，但缺口与东侧错开——两侧同时有口会让公路变成"漏斗"，
  // 玩家一眼看穿，反而没有"被夹在树篱之间"的压迫感。
  b.push(hedgeZ(10, 98, 82));
  b.push(hedgeZ(10, 74, 58));
  b.push(hedgeZ(10, 50, 30));
  b.push(hedgeZ(10, 22, 4));
  b.push(hedgeZ(10, -4, -16));

  // 土堤：树篱底部露出的石土。只放在几个田口两侧，纯视觉，不额外占碰撞
  //（和树篱同一位置会被合并感知，这里放在缺口边缘当"门柱"）
  b.push(hedgeZ(36, 67, 69, C_BANK));
  b.push(hedgeZ(36, 51, 53, C_BANK));
  b.push(hedgeZ(10, 75, 77, C_BANK));
  b.push(hedgeZ(10, 28, 30, C_BANK));

  // ---- 2. 田野分割 ----
  //
  // 东西向树篱把田野切成 30~40 m 见方的地块。这不只是装饰：
  // 它决定了"从公路拐进田野之后能不能横穿到另一条路"。
  // 东侧田野（x 36~98）
  b.push(hedgeX(88, 38, 98));
  b.push(hedgeX(58, 38, 98));
  b.push(hedgeX(26, 38, 98));
  b.push(hedgeX(-6, 38, 98));
  // 西侧田野（x -98~10）
  b.push(hedgeX(78, 8, -96));
  b.push(hedgeX(46, 8, -96));
  b.push(hedgeX(16, 8, -96));
  b.push(hedgeX(-14, 8, -96));

  // ---- 3. Point 213 林地 ----
  //
  // 玩家从这里出发。三面围合、只留西南一个开口通向土路：
  // 开局玩家看到的是"树影缝隙里一条横着的公路"，而不是"站在空地上看风景"。
  b.push(hedgeX(92, 48, 86));       // 北
  b.push(hedgeZ(86, 66, 94));       // 东
  b.push(hedgeX(66, 60, 86));       // 南（只到 x=60，西侧留口）
  b.push(hedgeZ(48, 82, 94));       // 西北段（只堵北半，南半开口）
  b.push(house(74, 86, 11, 8, 6.5, C_BARN));   // 213 农舍

  // 林地里的几丛树（矮、不成墙，只切视线）
  b.push([52, 86, 3.5, 6, 3.5, C_HEDGE]);
  b.push([68, 72, 4, 6, 4, C_HEDGE]);
  b.push([80, 78, 3, 5, 3, C_HEDGE]);

  // ---- 4. 镇区房屋 ----
  //
  // 两排石屋夹住主街，街宽 12 m（含两边人行道）。
  // 房屋之间留 3~4 m 的巷子：真实镇子几乎没有缝，但全封死的话
  // 玩家进镇就只剩一条线，巷战的可能性为零。
  // 北排（z 更小，街的北侧）
  b.push(house(-6, -42, 13, 9));
  b.push(house(-22, -44, 12, 9, 7, C_HOUSE2));
  b.push(house(-38, -46, 14, 9));
  b.push(house(-55, -42, 12, 9, 6.5, C_HOUSE2));
  b.push(house(-72, -38, 14, 9));
  b.push(house(-88, -36, 12, 9, 7, C_HOUSE2));
  // 南排
  b.push(house(-14, -8, 12, 9, 6.5, C_HOUSE2));
  b.push(house(-30, -10, 14, 9));
  b.push(house(-47, -14, 12, 9, 7, C_HOUSE2));
  b.push(house(-64, -18, 14, 9));
  b.push(house(-80, -22, 12, 9, 6.5, C_HOUSE2));
  // 镇口夹道：从公路进镇的第一眼，两侧各一栋，制造"进巷子"的感觉
  b.push(house(30, -34, 10, 9));
  b.push(house(32, -6, 10, 9, 6.5, C_HOUSE2));
  // 广场北侧一栋，给镇中心一个背景
  b.push(house(4, -50, 16, 9));

  return b.map(([x, z, w, h, d, color]) => ({ x, z, w, h, d, color }));
}

