// 波卡基村（Villers-Bocage）· 1944-06-13 0900 · N175 公路遭遇战
//
// 这是「经典战役」模式的第一关：玩家扮演魏特曼车组，从 213 高地北侧的树林出发，
// 沿土路下到 N175，撞上英军第 4 伦敦郡义勇骑兵团（4th CLY）A 中队的停驻纵队。
//
// ============ 坐标系与比例（必须先读） ============
//
// 世界坐标：+x 东、+z 南、-z 北（与 core/terrain.js 的 yaw 约定一致：yaw=0 朝 +z）。
// 于是"西北"= (-x, -z)，正是魏特曼 0900 的推进方向。
//
// 这不是等比例还原，是**关键拓扑还原 + 纵向距离压缩**：
//   真实镇中心到 Point 213 约 1.5 km，本图压缩到约 150 m（≈1:10）。
//   横向尺寸（路面 8~12 m、房屋 10~14 m、车长 6~7 m）一律按真实，不压缩。
//   原因是 15 m/s 的坦克在真实 1.5 km 上只要开 100 秒，中间没有任何决策点，
//   关卡会变成"按住 W 两分钟"。压缩纵向之后，三个决策点（土路口、队尾第一击、
//   镇口）落在 20~40 秒的间隔上，刚好是玩家观察—选择—行动一轮的长度。
//
// 相对的**位置关系**全部保留，这是这一关准确性的核心：
//   · 213 在公路东侧的一片高地上（图上用树林围合表示，见下面"高差"）
//   · 英军纵队停在公路上、车头朝东南（来路），两列交错，间距 6~8 m
//   · 镇子在西北端，街道沿 N175 转向，尽头是广场
//   · 公路两侧连续树篱（bocage），只有田口和土路能穿过去
//
// ============ 没有还原、以及为什么 ============
//
// 1. **高差**。引擎是平面地图（terrain.js 明确写了"没有 y 轴，就没有贴地问题"），
//    Point 213 的 213 米海拔无法表达。这里用"东侧树林围合 + 公路在更低处"的
//    视觉关系代替：玩家从树林里出来时，面前是一条横在脚下的公路。
//    真要加高差，建筑、单位、子弹全部要重做贴地，风险远大于收益。
// 2. **镇内街道的弯曲与建筑细节**。只保留"两排房屋夹一条街 + 尽头广场"的拓扑。
// 3. **个别车辆位置**。史料本身有争议（见 docs/boss-plan.md 之前记的罗生门），
//    这里按下述原则取"最保守的共识"：队尾是克伦威尔 + 萤火虫，队首靠近镇口，
//    A 中队有少量车辆散停在公路东侧田野。车号一律不标。
//
// ============ 玩家为什么"一炮就打得动" ============
//
// 真实是 88 mm KwK 36 对克伦威尔（正面 76 mm）——1000 m 内几乎必穿。
// 本关给玩家的是虎式数值（见 Game.startCampaign 的 CAMPAIGN_TUNING），
// 不是普通豹式：血量 ×3.4、单发 ×1.7、速度 ×0.72。
// 这样"停下来—瞄准—击发—换目标"的节奏才像虎式，而不是像街机。

